"""Reproducible complete postcut run, with saved intermediate geometry."""
import argparse, pickle, json, time, hashlib, dataclasses
from pathlib import Path
import numpy as np
from app_postcut_rebff import _execute
from postcut_rebff_full_pipeline import run_existing_pipeline_through_dual_hinge
from onestring_physics.onestring_pipeline import PipelineParameters
from onestring_physics import onestring_pipeline as pipe

def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('mesh',type=Path);ap.add_argument('--output',type=Path,required=True)
    ap.add_argument('--grid',type=int,default=15);ap.add_argument('--splits',type=int,default=8)
    ap.add_argument('--experiment-cache',type=Path,help='Trusted local pickle generated by this script only')
    ap.add_argument('--policy',choices=['fixed_initial_bff','legacy_joint_atlas'],default='fixed_initial_bff')
    ap.add_argument('--allow-unconverged-preview',action='store_true',help='Explicit diagnostic run despite CSF>2; does not certify fabrication')
    ap.add_argument('--standard',default='');ap.add_argument('--rectangle',default='')
    args=ap.parse_args();args.output.mkdir(parents=True,exist_ok=True)
    # Load precisely the dated UI's numerical patches, stopping before widgets.
    import runpy
    run_path=runpy.run_path
    def numerical_only(path, *a, **kw):
        if Path(path).name=='app_runtime_base.py': return {}
        return run_path(path,*a,**kw)
    runpy.run_path=numerical_only
    try: runpy.run_path(str(Path(__file__).with_name('app_optcuts_20260923_extrusion_aware.py')),run_name='__main__')
    finally: runpy.run_path=run_path
    def progress(*a):print(time.strftime('%H:%M:%S'),*a,flush=True)
    if args.experiment_cache:
        result=pickle.loads(args.experiment_cache.read_bytes())
    else:
        result=_execute(args.mesh,args.grid,args.standard,args.rectangle,0.,'曲率優先の最初のSplit','row',.5,'target_rectangle',max_splits=args.splits,progress=progress,geometry_policy=args.policy)
    (args.output/'experiment.pkl').write_bytes(pickle.dumps(result))
    (args.output/'split.json').write_text(json.dumps(result['report'],ensure_ascii=False,indent=2,default=str))
    params=PipelineParameters(nx=args.grid,ny=args.grid,max_3d_iterations=40,max_2d_iterations=40,hinge_layout_iterations=700,hinge_layout_time_budget_sec=30.,hinge_layout_restart_count=6,hinge_layout_search_mode='multi_start',hinge_layout_collision_mode='hard')
    for name in ['_lift_m2d_to_m3d','_optimize_k3d','_extrude_tiles','_optimize_k2d','_make_t2d_from_transforms','_optimize_dual_hinges']:
        base=getattr(pipe._original,name)
        def capture(*a,_base=base,_name=name,**kw):
            out=_base(*a,**kw)
            (args.output/(_name+'.pkl')).write_bytes(pickle.dumps(out))
            progress('SAVED',_name)
            return out
        setattr(pipe._original,name,capture)
    state,audit=run_existing_pipeline_through_dual_hinge(args.mesh,result,grid=args.grid,base_params=params,progress=progress,allow_csf_violation_preview=args.allow_unconverged_preview)
    (args.output/'state.pkl').write_bytes(pickle.dumps(state))
    (args.output/'audit.json').write_text(json.dumps(audit,indent=2,default=str))
    metadata=dict(input_sha256=hashlib.sha256(args.mesh.read_bytes()).hexdigest(),
                  parameters=dataclasses.asdict(params), geometry_policy=result['report'].get('geometry_policy','legacy_joint_atlas'))
    (args.output/'run.json').write_text(json.dumps(metadata,indent=2,default=str))
    arrays={}
    for name,mesh in [('M2D',state.mesh_2d_initial),('M3D',state.mesh_3d_initial),('K3D',state.mesh_3d_optimized),('K2D',state.mesh_2d_optimized)]:
        arrays[name+'_vertices']=mesh.vertices;arrays[name+'_faces']=mesh.faces
    arrays['S_vertices']=state.target_surface.vertices;arrays['S_faces']=state.target_surface.faces
    for name,assembly in [('T3D',state.tiles_3d),('T2D_top',state.tiles_2d_top_hinge),('T2D_dual',state.tiles_2d_dual_hinge)]:
        arrays[name]=assembly.vertices
    if hasattr(state.mesh_3d_optimized,'k3d_before_extrusion_vertices'):
        arrays['K3D_before_T3D_vertices']=state.mesh_3d_optimized.k3d_before_extrusion_vertices
    np.savez_compressed(args.output/'stages.npz',**arrays)
    progress('DONE',len(state.tiles_2d_dual_hinge.vertices))
if __name__=='__main__':main()
